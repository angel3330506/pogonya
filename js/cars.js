const DARK = 0x1d232b, GLASS = 0x26384a, TIRE = 0x1a1a1a, RIM = 0x9aa3ad, CHROME = 0xd8dde2,
  HEAD = 0xfff4c2, TAIL = 0xd2242a;

function wheel(v, x, z, r = 0.42, w = 0.38, rim = RIM) {
  v.wz.push(z);
  v.box(x, 0, z, w, r * 2, r * 2, TIRE);
  v.box(x + Math.sign(x) * (w / 2 + 0.01), r * 0.55, z, 0.04, r * 0.9, r * 0.9, rim);
}
function wheels4(v, x, zf, zr, r, w, rim) { wheel(v, x, zf, r, w, rim); wheel(v, -x, zf, r, w, rim); wheel(v, x, zr, r, w, rim); wheel(v, -x, zr, r, w, rim); }
function lights(v, w, zf, zr, y = 0.55) {
  v.box(w, y, zf, 0.36, 0.18, 0.06, HEAD); v.box(-w, y, zf, 0.36, 0.18, 0.06, HEAD);
  if (zr != null) { v.box(w, y, zr, 0.36, 0.16, 0.06, TAIL); v.box(-w, y, zr, 0.36, 0.16, 0.06, TAIL); }
}

// Обычный седан: основа для нескольких машин
