// Конус/цилиндр из «ступенек» (воксельный стиль)
function stack(v, x, y, z, w0, w1, h, n, c) {
  for (let i = 0; i < n; i++) {
    const t = n === 1 ? 0 : i / (n - 1), w = w0 + (w1 - w0) * t;
    v.box(x, y + (h / n) * i, z, w, h / n + 0.001, w, c);
  }
}

